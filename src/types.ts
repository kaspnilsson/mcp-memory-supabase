export interface Entity {
  name: string;
  entityType: string;
  observations: string[];
}

export interface Relation {
  from: string;
  to: string;
  relationType: string;
}

export interface KnowledgeGraph {
  entities: Entity[];
  relations: Relation[];
  [key: string]: unknown;
}

export interface SearchMatch extends Entity {
  similarity?: number;
}
